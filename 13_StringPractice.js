    // 5. Count consonants
    let consonants = 0;

    for (let char of str.toLowerCase()) {

        if (
            char >= "a" &&
            char <= "z" &&
            !(
                char === "a" ||
                char === "e" ||
                char === "i" ||
                char === "o" ||
                char === "u"
            )
        ) {
            consonants++;
        }
    }

