    let longest = words[0];

    for (let word of words) {

        if (word.length > longest.length) {
            longest = word;
        }
    }

    console.log("Q20 Longest Word:", longest);


    // 4. Count vowels
    let vowels = 0;

    for (let char of str.toLowerCase()) {

        if (
            char === "a" ||
            char === "e" ||
            char === "i" ||
            char === "o" ||
            char === "u"
        ) {
            vowels++;
        }
    }

