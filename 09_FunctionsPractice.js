function compose(...functions) {
    return function (value) {
        for (let i = functions.length - 1; i >= 0; i--) {
            value = functions[i](value);
        }

        return value;
    };
}

const addOne = x => x + 1;
const double = x => x * 2;

const result = compose(double, addOne);

console.log(result(5));