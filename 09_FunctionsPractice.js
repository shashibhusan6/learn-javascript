function isArmstrong(num) {
    let original = num;
    let sum = 0;
    let digits = num.toString().length;

    while (num > 0) {
        let digit = num % 10;
        sum += digit ** digits;
        num = Math.floor(num / 10);
    }

    return sum === original;
}

console.log(isArmstrong(153));
console.log(isArmstrong(123));


