function memoizedFactorial() {
    let cache = {};

    return function (num) {
        if (cache[num]) {
            console.log("Using Cached Value");
            return cache[num];
        }

        let fact = 1;

        for (let i = 1; i <= num; i++) {
            fact *= i;
        }

        cache[num] = fact;
        console.log("Calculated");

        return fact;
    };
}

const factorial = memoizedFactorial();

