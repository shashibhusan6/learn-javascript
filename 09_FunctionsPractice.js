function rotateArray(arr, k) {
    let result = [];
    let n = arr.length;

    k = k % n;

    for (let i = n - k; i < n; i++) {
        result.push(arr[i]);
    }

    for (let i = 0; i < n - k; i++) {
        result.push(arr[i]);
    }

    return result;
}

